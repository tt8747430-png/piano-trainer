import { chromium } from '@playwright/test'
const [file, out, w, theme='light'] = process.argv.slice(2)
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' })
const p = await b.newPage({ viewport: { width: +w, height: 900 }, colorScheme: theme })
const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()))
await p.goto('file://' + file); await p.waitForTimeout(1500)
const over = await p.evaluate(() => document.documentElement.scrollWidth - innerWidth)
await p.screenshot({ path: out, fullPage: true })
console.log('errors', errs, 'overflow', over, 'height', await p.evaluate(() => document.body.scrollHeight))
await b.close()
