// Imports the owner's Fantaisie-Impromptu, opens it in the Player as the installed app, plays 6 s,
// stops, and shoots: the piano while playing, after stopping, and what keys stay lit.
import { chromium } from '@playwright/test'
const [base, out] = process.argv.slice(2)
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium', args: ['--autoplay-policy=no-user-gesture-required'] })
const c = await b.newContext({ viewport: { width: 393, height: 852 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2 })
await c.addInitScript(() => { Object.defineProperty(navigator, 'standalone', { get: () => true }); if (!localStorage.getItem('pt-settings')) localStorage.setItem('pt-settings', JSON.stringify({ state: { welcomed: true }, version: 25 })) })
const p = await c.newPage()
const cdp = await c.newCDPSession(p)
await cdp.send('Emulation.setSafeAreaInsetsOverride', { insets: { top: 59, bottom: 34, left: 0, right: 0 } })
const errs = []; p.on('pageerror', (e) => errs.push(e.message))
await p.goto(base + '/songs'); await p.waitForTimeout(1500)
for (const name of ['Get started', 'Skip', 'Close']) { const b2 = p.getByRole('button', { name, exact: true }); if (await b2.count()) await b2.first().click().catch(() => {}) }
await p.getByRole('button', { name: 'New', exact: true }).click()
const [chooser] = await Promise.all([p.waitForEvent('filechooser'), p.getByRole('button', { name: 'Import', exact: true }).click()])
await chooser.setFiles('piano-data/scores/fantaisie-impromptu-in-c-minor-chopin.mxl')
await p.waitForTimeout(3000)
console.log('at', p.url())
const id = p.url().split('/songs/')[1]?.split(/[?#]/)[0]
await p.goto(`${base}/play/${id}`); await p.waitForTimeout(6000)
await p.screenshot({ path: `${out}/fi-rest.png` })
await p.getByRole('button', { name: 'Play', exact: true }).first().click()
await p.waitForTimeout(6000)
await p.screenshot({ path: `${out}/fi-playing.png` })
await p.getByRole('button', { name: /^(Stop|Pause)$/ }).first().click().catch((e) => console.log('no stop', e.message))
await p.waitForTimeout(2500)
await p.screenshot({ path: `${out}/fi-stopped.png` })
const lit = await p.evaluate(() => [...document.querySelectorAll('[aria-label$="2"],[aria-label$="3"],[aria-label$="4"],[aria-label$="5"],[aria-label$="6"]')].filter((k) => /^[A-G]( sharp| flat)? ?\d$/.test(k.getAttribute('aria-label') || '') && (k.dataset.sounding !== undefined || k.dataset.held !== undefined || k.getAttribute('data-state'))).map((k) => k.getAttribute('aria-label') + ':' + JSON.stringify(k.dataset)))
console.log('lit after stop', lit.slice(0, 20))
console.log('errors', errs)
await b.close()
