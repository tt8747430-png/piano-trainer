#!/usr/bin/env node
/**
 * Writes docs/INDEX.md: every part of the app's kit (shared/ui and its primitives), each widget,
 * feature, entity and page slice, every design token in src/styles/tokens.css and theme.css's
 * @theme, and every @utility in theme.css, each with what it is (its doc comment's first sentence)
 * and how many files use it. A count of 0 marks a part nothing uses. Run: node scripts/app-index.mjs
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, basename, dirname } from 'node:path'

const ROOT = new URL('..', import.meta.url).pathname
const SRC = join(ROOT, 'src')

/** Every source file under `dir`, tests and declarations left out. */
function files(dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name)
    if (statSync(path).isDirectory()) return files(path)
    return /\.(tsx?|css)$/.test(name) && !/\.test\.tsx?$|\.d\.ts$/.test(name) ? [path] : []
  })
}

const sources = files(SRC).map((path) => ({ path, text: readFileSync(path, 'utf8') }))
const rel = (path) => relative(ROOT, path)

/** The first sentence of the doc comment just above `name`'s declaration, or of the file. */
function about(text, name) {
  const at = name
    ? text.search(
        new RegExp(
          `export (?:default )?(?:async )?(?:function|const|class|interface|type) ${name}\\b`,
        ),
      )
    : -1
  const before = at >= 0 ? text.slice(0, at) : text.slice(0, 4000)
  const comments = [...before.matchAll(/\/\*\*([\s\S]*?)\*\//g)]
  const comment = at >= 0 ? comments.at(-1) : comments[0]
  if (!comment) return ''
  if (at >= 0 && before.slice(comment.index + comment[0].length).trim() !== '') return ''
  const plain = comment[1]
    .replace(/^\s*\* ?/gm, ' ')
    .replace(/\s+/g, ' ')
    .trim()
  const sentence = plain.match(/^.*?[.:](?=\s|$)/)
  return (sentence ? sentence[0] : plain).replace(/\|/g, '\\|').slice(0, 180)
}

/** How many files other than `skip` mention `word` as a whole word. */
function uses(word, skip) {
  const pattern = new RegExp(`(?<![\\w$-])${word.replace(/[$]/g, '\\$')}(?![\\w$])`)
  return sources.filter(({ path, text }) => !skip.includes(path) && pattern.test(text)).length
}

const lines = [
  '# App index',
  '',
  'Generated by `node scripts/app-index.mjs`; do not edit by hand. Each part of the app with what it',
  'is (its doc comment) and how many files use it. **0** marks a part nothing uses.',
  '',
]

// The kit: each export of shared/ui's index, with the file it comes from.
const KIT = join(SRC, 'shared/ui')
const kitIndex = readFileSync(join(KIT, 'index.ts'), 'utf8')
const kitRows = []
for (const match of kitIndex.matchAll(/export \{([^}]+)\} from '(\.[^']+)'/g)) {
  const from = match[2]
  const candidates = [`${from}.tsx`, `${from}.ts`, `${from}/index.ts`].map((f) => join(KIT, f))
  const file = candidates.find((f) => sources.some((s) => s.path === f))
  const text = file ? readFileSync(file, 'utf8') : ''
  for (const raw of match[1].split(',')) {
    const name = raw
      .replace(/^\s*type\s+/, '')
      .split(/\s+as\s+/)
      .pop()
      .trim()
    if (!name) continue
    const own = file ? [file, join(KIT, 'index.ts')] : [join(KIT, 'index.ts')]
    kitRows.push({
      name,
      file: file ? rel(file) : from,
      about: about(text, name),
      count: uses(name, own),
    })
  }
}
lines.push(
  '## The kit (`src/shared/ui`)',
  '',
  '| Part | File | What it is | Used by |',
  '| --- | --- | --- | --- |',
)
for (const row of kitRows.sort((a, b) => a.name.localeCompare(b.name)))
  lines.push(
    `| \`${row.name}\` | \`${row.file}\` | ${row.about} | ${row.count === 0 ? '**0**' : row.count} |`,
  )

// The primitives (shadcn), imported by path.
const PRIM = join(KIT, 'primitives')
lines.push(
  '',
  '## Primitives (`src/shared/ui/primitives`, shadcn)',
  '',
  '| Primitive | Exports | Used by |',
  '| --- | --- | --- |',
)
for (const name of readdirSync(PRIM)
  .filter((n) => /\.tsx$/.test(n) && !n.includes('.test.'))
  .sort()) {
  const path = join(PRIM, name)
  const stem = name.replace(/\.tsx$/, '')
  const count = sources.filter(
    (s) => s.path !== path && s.text.includes(`primitives/${stem}'`),
  ).length
  const exported = [...readFileSync(path, 'utf8').matchAll(/export \{([^}]+)\}/g)].flatMap((m) =>
    m[1]
      .split(',')
      .map((x) => x.trim())
      .filter(Boolean),
  )
  lines.push(`| \`${stem}\` | ${exported.join(', ')} | ${count === 0 ? '**0**' : count} |`)
}

// The slices: widgets, features, entities, pages, each with its index's summary and its users.
for (const layer of ['widgets', 'features', 'entities', 'pages']) {
  const dir = join(SRC, layer)
  lines.push(
    '',
    `## ${layer[0].toUpperCase()}${layer.slice(1)} (\`src/${layer}\`)`,
    '',
    '| Slice | What it is | Used by |',
    '| --- | --- | --- |',
  )
  for (const slice of readdirSync(dir)
    .filter((n) => statSync(join(dir, n)).isDirectory())
    .sort()) {
    const inside = join(dir, slice) + '/'
    const index = sources.find((s) => s.path === join(dir, slice, 'index.ts'))
    const first = index ? about(index.text, null) : ''
    const fromIndex = index ? (index.text.match(/from '\.\/([^']+)'/) ?? [])[1] : undefined
    const lead = fromIndex
      ? sources.find((s) => s.path.startsWith(join(dir, slice, fromIndex)))
      : undefined
    const summary = first || (lead ? about(lead.text, null) : '')
    const count = sources.filter(
      (s) => !s.path.startsWith(inside) && s.text.includes(`@/${layer}/${slice}'`),
    ).length
    lines.push(
      `| \`${slice}\` | ${summary} | ${layer === 'pages' ? count : count === 0 ? '**0**' : count} |`,
    )
  }
}

// The tokens: custom properties declared in tokens.css and theme.css.
const tokenFiles = ['src/styles/tokens.css', 'src/styles/theme.css'].map((f) => join(ROOT, f))
const declared = new Map()
for (const file of tokenFiles)
  for (const m of readFileSync(file, 'utf8').matchAll(/^\s*(--[a-z0-9-]+)\s*:/gm))
    if (!declared.has(m[1])) declared.set(m[1], rel(file))
/** A token's uses: `var(--x)` anywhere, or its Tailwind class (`--color-ink` → `-ink`, `--radius-card` → `rounded-card`). */
const TAILWIND = {
  color: '',
  radius: 'rounded-',
  spacing: '',
  shadow: 'shadow-',
  font: 'font-',
  text: 'text-',
  ease: 'ease-',
  animate: 'animate-',
  tracking: 'tracking-',
  'inset-shadow': 'inset-shadow-',
  breakpoint: '',
  container: '',
}
function tokenUses(token) {
  // `var(--x)`, Tailwind's `(--x)`, or a name built from a template (`var(--block-radius-${n})`).
  const prefix = token.replace(/-[^-]+$/, '-')
  const varUse = (s) =>
    s.text.includes(`var(${token})`) ||
    s.text.includes(`var(${token},`) ||
    s.text.includes(`(${token})`) ||
    s.text.includes(`var(${prefix}\${`)
  const [, ns, rest] = token.match(/^--([a-z]+(?:-shadow)?)-(.+)$/) ?? []
  let classUse = () => false
  if (ns && ns in TAILWIND) {
    const suffix = ns === 'breakpoint' ? `${rest}:` : `${TAILWIND[ns]}${rest}`
    const re =
      ns === 'color' || ns === 'spacing' || ns === 'container'
        ? new RegExp(`[a-z]-${rest}(?![\\w-])`)
        : ns === 'radius'
          ? new RegExp(`(?<![\\w-])rounded-(?:[trblsexy]{1,2}-)?${rest}(?![\\w-])`)
          : new RegExp(`(?<![\\w-])${suffix.replace(/[:]/g, '\\:')}(?![\\w-])`)
    classUse = (s) => /\.(tsx?)$/.test(s.path) && re.test(s.text)
  }
  return sources.filter(
    (s) =>
      varUse(s) ||
      classUse(s) ||
      (s.path.endsWith('.css') &&
        new RegExp(`(?<![\\w-])${token}(?![\\w-])\\s*[^:]`).test(
          s.text.replace(new RegExp(`^\\s*${token}\\s*:`, 'gm'), ''),
        )),
  ).length
}
lines.push(
  '',
  '## Tokens (`src/styles/tokens.css`, `theme.css`)',
  '',
  'Primitives (`--p-*`) are read by the roles only; a role is used through `var()` or its Tailwind class.',
  '',
  '| Token | Declared in | Used by |',
  '| --- | --- | --- |',
)
// A size's own line height (`--text-xl--line-height`) is read by its size's class.
for (const [token, file] of [...declared].filter(([t]) => !t.includes('--line-height')).sort()) {
  const count = tokenUses(token)
  // Tailwind's own corner sizes, mapped onto the scale so a primitive's class lands on it (shapes.test.ts).
  const guard = /^--radius-(xs|sm|md|lg|xl|2xl|3xl|4xl)$/.test(token)
  lines.push(
    `| \`${token}\` | \`${file}\` | ${count === 0 ? (guard ? "0, kept: a primitive's size mapped onto the scale" : '**0**') : count} |`,
  )
}

// The utilities: @utility names in theme.css.
const theme = readFileSync(join(SRC, 'styles/theme.css'), 'utf8')
lines.push(
  '',
  '## Utilities (`@utility` in `src/styles/theme.css`)',
  '',
  '| Utility | What it is | Used by |',
  '| --- | --- | --- |',
)
for (const m of theme.matchAll(/(?:\/\*\s*([\s\S]*?)\*\/\s*)?@utility ([a-z0-9-]+(?:\*)?)/g)) {
  // A functional utility (`pb-foot-*`) is used as its stem and a value.
  const name = m[2].endsWith('-*') ? m[2].slice(0, -1) + '[a-z0-9.()-]+' : m[2]
  const re = new RegExp(`(?<![\\w-])(?:[a-z0-9-]+:)*${name}(?![\\w-])`)
  const count =
    sources.filter((s) => /\.tsx?$/.test(s.path) && re.test(s.text)).length +
    sources.filter(
      (s) =>
        s.path.endsWith('.css') &&
        new RegExp(`@apply[^;]*(?<![\\w-])${name}(?![\\w-])`).test(s.text),
    ).length
  const note =
    (m[1] ?? '')
      .replace(/\s+/g, ' ')
      .trim()
      .match(/^.*?[.:](?=\s|$)/)?.[0] ?? ''
  lines.push(
    `| \`${m[2]}\` | ${note.replace(/\|/g, '\\|').slice(0, 160)} | ${count === 0 ? '**0**' : count} |`,
  )
}

writeFileSync(join(ROOT, 'docs/INDEX.md'), lines.join('\n') + '\n')
const zero = lines.filter((l) => l.endsWith('| **0** |')).length
console.log(`docs/INDEX.md: ${lines.length} lines, ${zero} parts used by nothing`)
